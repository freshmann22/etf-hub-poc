function computeTopHoldings(etfId) {
  return holdings
    .filter((h) => h.etfId === etfId)
    .sort((a, b) => a.rank - b.rank)
    .map((h) => h.stockId);
}

function computeRelatedEtfIds(stockId) {
  const ids = [];
  holdings
    .filter((h) => h.stockId === stockId)
    .forEach((h) => {
      if (!ids.includes(h.etfId)) ids.push(h.etfId);
    });
  return ids;
}

